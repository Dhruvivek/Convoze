/// The app's spacing scale, so gaps and padding come from one shared set of
/// values instead of ad hoc numbers scattered per screen.
abstract final class AppSpacing {
  static const xs = 4.0;
  static const sm = 8.0;
  static const md = 12.0;
  static const lg = 16.0;
  static const xl = 24.0;
  static const xxl = 32.0;
  static const xxxl = 48.0;
}
